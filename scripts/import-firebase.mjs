#!/usr/bin/env node
/**
 * One-time move of the old Firebase data into NeatSystem's Supabase.
 *
 *   node scripts/import-firebase.mjs
 *
 * It asks for the Firebase web config of StudentTracker and of NeatHub, reads
 * Firestore from your machine, and writes SQL files into firebase-import/.
 * Then: Supabase → SQL Editor → paste each file → Run, in the order printed.
 * Nothing is sent anywhere else. Running the SQL again is safe (no duplicates).
 *
 * Needs the sub-system checkouts (git submodule update --init) and Node 18+.
 */
import { createInterface } from 'node:readline/promises'
import { mkdirSync, writeFileSync, existsSync, readdirSync, rmSync } from 'node:fs'
import { stdin, stdout } from 'node:process'
import { buildImport, readFirestore, fromDoc } from '../systems/trainings/src/model/firestore.js'

const OUT = 'firebase-import'
const CHUNK = 40_000 // characters of data per SQL file: the SQL editor cuts off long pastes
const TAG = '$fsimport$'

// interactive in a terminal; answers can also be piped in, one per line
const piped = !stdin.isTTY ? (await new Promise((res) => { let d = ''; stdin.on('data', (c) => (d += c)); stdin.on('end', () => res(d.split(/\r?\n/))) })) : null
const rl = piped ? { close() {} } : createInterface({ input: stdin, output: stdout })
const ask = async (q, def = '') => {
  if (piped) { const a = (piped.shift() ?? '').trim() || def; console.log(`${q}: ${a ? '•••' : ''}`); return a }
  return (await rl.question(def ? `${q} [${def}]: ` : `${q}: `)).trim() || def
}

function sqlJson(value) {
  const s = JSON.stringify(value)
  if (s.includes(TAG)) throw new Error('unexpected text in the data')
  return `${TAG}${s}${TAG}::jsonb`
}

// ---------------------------------------------------------------- StudentTracker
async function trainings(projectId, apiKey) {
  console.log('\nקורא את StudentTracker…')
  const fs = await readFirestore(projectId, apiKey)
  const { payload, counts } = buildImport(fs)
  console.log(`  ${counts.people} אנשים · ${counts.categories} קטגוריות · ${counts.items} פריטים · ${counts.certs} הסמכות · ${counts.events} רשומות יומן`)
  // split into small calls: each carries the people (to match them) and a slice of the records;
  // the first one also the catalog, the last one the locked leads
  const { categories, items, rules, people, locked_leads, ...lists } = payload
  const base = JSON.stringify(people).length
  const parts = [{ categories, items, rules, people }]
  let size = base + JSON.stringify([categories, items, rules]).length
  for (const [k, rows] of Object.entries(lists)) {
    for (const r of rows) {
      const n = JSON.stringify(r).length + 1
      if (size + n > CHUNK) { parts.push({ people }); size = base }
      const cur = parts[parts.length - 1]
      ;(cur[k] ??= []).push(r)
      size += n
    }
  }
  parts[parts.length - 1].locked_leads = locked_leads
  return parts.map((part, i) => ({
    name: `trainings-${i + 1}.sql`,
    sql: `-- StudentTracker → trainings, part ${i + 1}/${parts.length}. Generated by scripts/import-firebase.mjs. Safe to run again.
-- The result shows how many people matched a NeatSystem member, and the names that didn't
-- (their records are kept; link them later with:  select trainings.link_legacy('שם', 'email');)
select jsonb_pretty(trainings.import_firestore(${sqlJson(part)}));
`,
  }))
}

// ---------------------------------------------------------------- NeatHub
async function idToken(apiKey, refreshToken) {
  const r = await fetch(`https://securetoken.googleapis.com/v1/token?key=${encodeURIComponent(apiKey)}`, {
    method: 'POST', headers: { 'content-type': 'application/x-www-form-urlencoded' },
    body: `grant_type=refresh_token&refresh_token=${encodeURIComponent(refreshToken)}`,
  })
  if (!r.ok) throw new Error(`ה-token של NeatHub לא עבד (${r.status}). אפשר להשאיר ריק ולייבא רק קישורים ציבוריים.`)
  return (await r.json()).id_token
}
async function readCollection(projectId, apiKey, name, token) {
  const out = []
  let page = ''
  do {
    const u = `https://firestore.googleapis.com/v1/projects/${encodeURIComponent(projectId)}/databases/(default)/documents/${name}?pageSize=300&key=${encodeURIComponent(apiKey)}${page ? `&pageToken=${encodeURIComponent(page)}` : ''}`
    const r = await fetch(u, token ? { headers: { Authorization: `Bearer ${token}` } } : undefined)
    if (r.status === 403) return null // not readable without signing in
    if (!r.ok) throw new Error(`NeatHub ${name}: ${r.status} ${(await r.text()).slice(0, 120)}`)
    const j = await r.json()
    for (const d of j.documents ?? []) out.push(fromDoc(d))
    page = j.nextPageToken ?? ''
  } while (page)
  return out
}
// a URL document can be read one by one when the collection as a whole can't (public ones)
async function readDoc(projectId, apiKey, path, token) {
  const u = `https://firestore.googleapis.com/v1/projects/${encodeURIComponent(projectId)}/databases/(default)/documents/${path}?key=${encodeURIComponent(apiKey)}`
  const r = await fetch(u, token ? { headers: { Authorization: `Bearer ${token}` } } : undefined)
  return r.ok ? fromDoc(await r.json()) : null
}

const VIS = new Set(['public', 'members', 'leads', 'mentors'])
const http = (u) => (typeof u === 'string' && /^https?:\/\/.+/.test(u) && u.length < 2000 ? u : null)

async function neathub(projectId, apiKey, refreshToken) {
  console.log('\nקורא את NeatHub…')
  const token = refreshToken ? await idToken(apiKey, refreshToken) : null
  const raw = await readCollection(projectId, apiKey, 'nodes', token)
  if (!raw) throw new Error('אין גישה ל-nodes של NeatHub (בדקו project id ו-API key)')
  let urls = await readCollection(projectId, apiKey, 'nodeUrls', token)
  if (!urls) urls = (await Promise.all(raw.filter((n) => n.type === 'link').map((n) => readDoc(projectId, apiKey, `nodeUrls/${n.id}`, token)))).filter(Boolean)
  const users = token ? (await readCollection(projectId, apiKey, 'users', token)) ?? [] : []

  // parents before children; keep only what the tables accept
  const byId = new Map(raw.map((n) => [n.id, n]))
  const depth = (n, seen = new Set()) => (!n.parentId || seen.has(n.id) || !byId.get(n.parentId) ? 0 : 1 + depth(byId.get(n.parentId), seen.add(n.id)))
  const slugs = new Set()
  const nodes = raw.filter((n) => /^[A-Za-z0-9_-]{1,40}$/.test(n.id) && (n.type === 'hub' || n.type === 'link')).sort((a, b) => depth(a) - depth(b)).map((n) => {
    let slug = typeof n.slug === 'string' && /^[a-z0-9][a-z0-9-]{0,39}$/.test(n.slug) ? n.slug : null
    if (slug && slugs.has(`${n.parentId ?? ''}/${slug}`)) slug = null
    if (slug) slugs.add(`${n.parentId ?? ''}/${slug}`)
    const visibility = VIS.has(n.visibility) ? n.visibility : 'public'
    return {
      id: n.id, parent_id: n.parentId ?? null, type: n.type, title: String(n.title ?? n.id).slice(0, 60) || n.id,
      label_mode: ['txt', 'img', 'both'].includes(n.labelMode) ? n.labelMode : 'txt', label_text: n.labelText ? String(n.labelText).slice(0, 60) : null,
      image_data: typeof n.imageData === 'string' && n.imageData.length < 300000 ? n.imageData : null,
      image_url: http(n.imageUrl), image_fallback: http(n.imageFallback),
      season: n.type === 'hub' ? Number(n.season) || 2026 : n.season ?? null, slug, piece: n.piece ?? null,
      visibility, eff_vis: VIS.has(n.effVis) ? n.effVis : visibility, scope: n.scope ?? (n.type === 'hub' && !n.parentId ? n.id : 'root'), sort: Number(n.order) || 0,
    }
  })
  const urlRows = urls.map((u) => ({ id: u.id, url: http(u.url) })).filter((u) => u.url && nodes.some((n) => n.id === u.id))
  const scopes = users.filter((u) => u.email && Array.isArray(u.scopes) && u.scopes.length).map((u) => ({ email: u.email, scopes: u.scopes }))
  const links = nodes.filter((n) => n.type === 'link').length
  console.log(`  ${nodes.length - links} ארגזים · ${links} קישורים · ${urlRows.length} כתובות${urlRows.length < links ? ` (${links - urlRows.length} נעולות — הוסיפו את ה-token כדי לקבל גם אותן)` : ''}${scopes.length ? ` · הרשאות עריכה ל-${scopes.length} אנשים` : ''}`)

  // a big picture doesn't fit in one paste: it's written afterwards in pieces (image_pieces)
  const big = []
  for (const n of nodes) if (n.image_data && n.image_data.length > CHUNK / 2) { big.push([n.id, n.image_data]); n.image_data = null }
  const files = []
  let part = [], size = 0
  const flush = () => { if (part.length) files.push(part); part = []; size = 0 }
  for (const n of nodes) { const s = JSON.stringify(n).length; if (size + s > CHUNK) flush(); part.push(n); size += s }
  flush()
  const pieces = []
  for (const [id, data] of big) for (let o = 0; o < data.length; o += CHUNK) pieces.push({ id, first: o === 0, data: data.slice(o, o + CHUNK) })
  const n = files.length + pieces.length
  return [...files.map((chunk, i) => ({
    name: `neathub-${i + 1}.sql`,
    sql: `-- NeatHub nodes, part ${i + 1}/${n}. Generated by scripts/import-firebase.mjs. Safe to run again (in order).
insert into neathub.nodes as t (id, parent_id, type, title, label_mode, label_text, image_data, image_url, image_fallback, season, slug, piece, visibility, eff_vis, scope, sort)
select id, parent_id, type, title, label_mode, label_text, image_data, image_url, image_fallback, season, slug, piece, visibility, eff_vis, scope, sort
from jsonb_to_recordset(${sqlJson(chunk)}) as x(id text, parent_id text, type text, title text, label_mode text, label_text text, image_data text, image_url text,
  image_fallback text, season int, slug text, piece text, visibility text, eff_vis text, scope text, sort double precision)
on conflict (id) do update set parent_id = excluded.parent_id, type = excluded.type, title = excluded.title, label_mode = excluded.label_mode,
  label_text = excluded.label_text, image_data = excluded.image_data, image_url = excluded.image_url, image_fallback = excluded.image_fallback,
  season = excluded.season, slug = excluded.slug, piece = excluded.piece, visibility = excluded.visibility, eff_vis = excluded.eff_vis,
  scope = excluded.scope, sort = excluded.sort, updated_at = now();
` + (i === files.length - 1 ? `
-- the link addresses
insert into neathub.urls (id, url)
select id, url from jsonb_to_recordset(${sqlJson(urlRows)}) as x(id text, url text)
where exists (select 1 from neathub.nodes n where n.id = x.id)
on conflict (id) do update set url = excluded.url;

-- who edits which tote (by the same Google email in NeatSystem)
insert into neathub.scopes (user_id, scope)
select p.id, s from jsonb_to_recordset(${sqlJson(scopes)}) as x(email text, scopes jsonb)
join hub.profiles p on lower(p.email) = lower(x.email), jsonb_array_elements_text(x.scopes) s
where s = 'root' or exists (select 1 from neathub.nodes n where n.id = s and n.parent_id is null and n.type = 'hub')
on conflict do nothing;

select (select count(*) from neathub.nodes) as nodes, (select count(*) from neathub.urls) as urls, (select count(*) from neathub.scopes) as edit_permissions;
` : ''),
  })), ...pieces.map((p, j) => ({
    name: `neathub-${files.length + j + 1}.sql`,
    sql: `-- NeatHub, part ${files.length + j + 1}/${n}: a piece of a big picture. Generated by scripts/import-firebase.mjs. Safe to run again (in order).
update neathub.nodes set image_data = ${p.first ? '' : 'image_data || '}${TAG}${p.data.replaceAll(TAG, '')}${TAG} where id = ${TAG}${p.id}${TAG};
`,
  }))]
}

// ---------------------------------------------------------------- main
const TOKEN_SNIPPET = `indexedDB.open('firebaseLocalStorageDb').onsuccess=e=>e.target.result.transaction('firebaseLocalStorage').objectStore('firebaseLocalStorage').getAll().onsuccess=r=>console.log(r.target.result.map(x=>x.value?.stsTokenManager?.refreshToken).find(Boolean))`

try {
  if (!existsSync('systems/trainings/src/model/firestore.js')) throw new Error('חסרה התיקייה systems/trainings — להריץ קודם: git submodule update --init')
  console.log('ייבוא מ-Firebase ל-NeatSystem. הערכים נמצאים ב-Firebase console → Project settings → Your apps (או ב-.env הישן).')
  console.log('\n— StudentTracker (Enter לדילוג) —')
  const stProject = await ask('project id')
  const stKey = stProject ? await ask('web API key') : ''
  console.log('\n— NeatHub (Enter לדילוג) —')
  const nhProject = await ask('project id')
  const nhKey = nhProject ? await ask('web API key') : ''
  let nhToken = ''
  if (nhProject) {
    console.log('\nבשביל הקישורים הנעולים ו"מי עורך מה": לפתוח את NeatHub הישן מחובר/ת כמנטור/ית, F12 → Console, להדביק את השורה הבאה ולהעתיק את מה שיודפס:')
    console.log(`\n${TOKEN_SNIPPET}\n`)
    nhToken = await ask('token (Enter לדילוג — ייובאו רק הקישורים הציבוריים)')
  }
  rl.close()

  const files = [...(stProject ? await trainings(stProject, stKey) : []), ...(nhProject ? await neathub(nhProject, nhKey, nhToken) : [])]
  if (!files.length) { console.log('לא נבחר כלום.'); process.exit(0) }
  if (existsSync(OUT)) for (const f of readdirSync(OUT)) rmSync(`${OUT}/${f}`)
  mkdirSync(OUT, { recursive: true })
  files.forEach((f, i) => writeFileSync(`${OUT}/${i + 1}-${f.name}`, f.sql))
  console.log(`\nנוצרו ${files.length} קבצים ב-${OUT}/. ב-Supabase → SQL Editor, להדביק ולהריץ לפי הסדר:`)
  files.forEach((f, i) => console.log(`  ${i + 1}. ${OUT}/${i + 1}-${f.name}`))
  console.log('\nהתיקייה מוחרגת מ-git (יש בה שמות וטלפונים). אחרי הייבוא אפשר למחוק אותה.')
} catch (e) {
  rl.close()
  console.error(`\nשגיאה: ${e.message}`)
  process.exit(1)
}
